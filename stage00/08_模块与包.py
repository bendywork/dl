# --------------------------------------------------------
# 知识点：模块导入 —— import module
# 模块是包含 Python 定义和语句的文件
# 一个模块被第一次导入时，会执行该模块
# 习惯上把所有导入语句放在模块开头
# --------------------------------------------------------
import os
print(os.getcwd())  # 使用 os 模块的函数


# --------------------------------------------------------
# 知识点：模块导入 —— import module as alias
# 给模块起别名，避免命名冲突或简化书写
# --------------------------------------------------------
import os as operating_system
print(operating_system.path.sep)


# --------------------------------------------------------
# 知识点：模块导入 —— from module import item
# 只导入模块中的某个具体名称（变量、函数、类等）
# --------------------------------------------------------
from os import getcwd
print(getcwd())


# --------------------------------------------------------
# 知识点：模块导入 —— from module import item as alias
# 导入具体名称并起别名
# --------------------------------------------------------
from os import getcwd as get_current_dir
print(get_current_dir())


# --------------------------------------------------------
# 知识点：模块导入 —— from module import *
# 导入模块中所有公开的名称
# 注意：慎用！很容易出现名称重复，导致意外问题
# --------------------------------------------------------
from os.path import *
print(sep)      # os.path.sep 直接使用
print(join('/tmp', 'test'))


# --------------------------------------------------------
# 知识点：包的导入 —— import package
# 包本质上是包含 __init__.py 的文件夹
# 可以避免模块命名冲突，也方便对模块进行分类管理
# --------------------------------------------------------
import email
print(email.__name__)


# --------------------------------------------------------
# 知识点：包的导入 —— import package as alias
# 给包起别名
# --------------------------------------------------------
import email as em
print(em.__name__)


# --------------------------------------------------------
# 知识点：包的导入 —— from package import module
# 从包中导入某个模块
# --------------------------------------------------------
from email import mime
print(mime.__name__)


# --------------------------------------------------------
# 知识点：包的导入 —— from package import module as alias
# 从包中导入某个模块并起别名
# --------------------------------------------------------
from email import mime as m
print(m.__name__)


# --------------------------------------------------------
# 知识点：包的导入 —— from package.module import item
# 从包的某个模块中导入具体名称
# --------------------------------------------------------
from email.mime.text import MIMEText
msg = MIMEText('Hello, this is a test email.')
print(type(msg))


# --------------------------------------------------------
# 知识点：包的导入 —— from package.module import item as alias
# 从包的某个模块中导入具体名称并起别名
# --------------------------------------------------------
from email.mime.text import MIMEText as MT
msg2 = MT('Hello again.')
print(type(msg2))


# --------------------------------------------------------
# 知识点：搜索路径 —— sys.path
# sys.path 以列表形式记录了 Python 解释器自动查找模块/包的路径
# 如果所有路径都找不到，会报错：ModuleNotFoundError: No module named 'xxx'
# --------------------------------------------------------
import sys
print(sys.path)


# --------------------------------------------------------
# 知识点：__name__ 属性
# 每个模块都有 __name__ 属性
# 直接运行时：__name__ == '__main__'
# 被其他程序导入时：__name__ == 模块名
# 常用于将测试代码隔离，避免被导入时执行
# --------------------------------------------------------
def add(x, y):
    print(x + y)
    print(x * 2)

if __name__ == '__main__':
    add(3, 4)
    add('3', '4')

